  void detect(const TensorPtr& score_map, const DetectParams& params, Keypoints* out) override {
    const MetalTensor& sm = dev(score_map);
    const int w = sm.w, h = sm.h, n = w * h;
    const View s = sm.d();
    out->xy_norm.clear();
    out->score.clear();
    if (n == 0) return;
    if (sm.half) fail("detect needs a float score map");
    ctx_->tag(format("detect %dx%d", w, h));

    // Non-maximum suppression (simple_nms from SuperGlue, two refinement rounds).
    Buffer<float> nms(ctx_, n);
    {
      Buffer<float> tmp(ctx_, n), mask(ctx_, n), pooled_mask(ctx_, n), supp(ctx_, n), pooled_supp(ctx_, n);
      auto max_filter = [&](const View& src, const View& dst) {
        ctx_->run("k_max_filter", n, src, w, h, kRadius, 0, tmp.view());
        ctx_->run("k_max_filter", n, tmp.view(), w, h, kRadius, 1, dst);
      };
      max_filter(s, pooled_supp.view());
      ctx_->run("k_nms_init", n, s, pooled_supp.view(), n, mask.view());
      for (int round = 0; round < 2; ++round) {
        max_filter(mask.view(), pooled_mask.view());
        ctx_->run("k_nms_suppress", n, s, pooled_mask.view(), n, supp.view());
        max_filter(supp.view(), pooled_supp.view());
        ctx_->run("k_nms_update", n, supp.view(), pooled_supp.view(), pooled_mask.view(), n, mask.view());
      }
      ctx_->run("k_nms_final", n, s, mask.view(), w, h, kRadius, nms.view());
    }

    // Selection, on the device. `idx` receives the pixel indices of the keypoints in output order.
    Selection select(ctx_, nms.view(), n);
    int kept = 0;         // number of keypoints
    int best = -1;        // >= 0: keep the `best` highest scores, best first
    float threshold = 0;  // otherwise: keep nms > threshold, in raster order
    if (params.top_k > 0) {
      best = std::min(params.top_k, n);
    } else {
      int passing = params.scores_th > 0 ? select.count(kGreater, threshold = params.scores_th) : 0;
      if (passing == 0) {  // fall back to the mean score, summed in raster order like the CPU backend
        ctx_->sync();
        const float* v = reinterpret_cast<const float*>(sm.host());
        float total = 0;
        for (int i = 0; i < n; ++i) total += v[i];
        passing = select.count(kGreater, threshold = total / static_cast<float>(n));
      }
      if (passing > params.n_limit) best = std::max(0, params.n_limit);
      else kept = passing;
    }
    if (best >= 0) kept = best;
    if (kept == 0) return;

    Buffer<int> idx(ctx_, kept);
    if (best < 0) select.write(kGreater, threshold, kept, idx.view());
    else select.top(best, idx.view());

    // Refinement and readback of the kept keypoints only.
    Buffer<float> xy(ctx_, 2 * static_cast<size_t>(kept)), score(ctx_, kept);
    ctx_->run("k_refine", kept, s, w, h, idx.view(), kept, xy.view(), score.view());
    ctx_->sync();
    out->xy_norm.assign(xy.host(), xy.host() + 2 * static_cast<size_t>(kept));
    out->score.assign(score.host(), score.host() + kept);
  }

