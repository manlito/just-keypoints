enum : int { kActNone = 0, kActSelu = 1, kActSigmoid = 2 };
enum : int { kGreater = 0, kEqual = 1 };
constexpr int kRadius = 2;       // NMS and soft-argmax window radius
constexpr int kScanBlock = 256;  // elements handled by one thread in the compaction kernels

[[noreturn]] void fail(const std::string& what) { throw std::runtime_error("metal: " + what); }

std::string format(const char* fmt, ...) {
  char buf[160];
  va_list args;
  va_start(args, fmt);
  std::vsnprintf(buf, sizeof(buf), fmt, args);
  va_end(args);
  return buf;
}

std::string describe_error(NSError* error) {
  return error ? std::string([[error localizedDescription] UTF8String]) : std::string("unknown error");
}

// Element count as int; the kernels index with 32-bit integers.
int count(long long n) {
  if (n < 0 || n > INT_MAX) fail("tensor too large");
  return static_cast<int>(n);
}

// A buffer bound to a kernel argument, at a byte offset.
struct View {
  id<MTLBuffer> buffer;
  size_t offset = 0;
};

// Device, queue, compiled kernels, the open command buffer and the buffer pool. Shared by the backend
// and every tensor it created, so a tensor can flush pending work before it is read.
class Context {
 public:
  explicit Context(int index) {
    const char* env = std::getenv("JKP_METAL_PROFILE");
    profile_ = env && *env && std::string(env) != "0";
    @autoreleasepool {
      NSArray<id<MTLDevice>>* devices = MTLCopyAllDevices();
      if (devices.count == 0) fail("no Metal device found");
      if (index < 0 || index >= static_cast<int>(devices.count))
        fail("device " + std::to_string(index) + " not found (" + std::to_string(devices.count) + " available)");
      device_ = devices[index];
      queue_ = [device_ newCommandQueue];
      if (!queue_) fail("cannot create a command queue");

      MTLCompileOptions* options = [[MTLCompileOptions alloc] init];
      if (@available(macOS 15.0, iOS 18.0, *)) {
        options.mathMode = MTLMathModeSafe;
        options.mathFloatingPointFunctions = MTLMathFloatingPointFunctionsPrecise;
      } else {
#pragma clang diagnostic push
#pragma clang diagnostic ignored "-Wdeprecated-declarations"
        options.fastMathEnabled = NO;
#pragma clang diagnostic pop
      }
      NSError* error = nil;
      library_ = [device_ newLibraryWithSource:@(kJkpMetalSource) options:options error:&error];
      if (!library_) fail("shader compilation failed: " + describe_error(error));
    }
  }

  ~Context() {
    try {
      sync();
    } catch (...) {
    }
    if (profile_) report();
  }

  // Profiling label for the dispatches that follow (the operation and its shape).
  void tag(std::string t) {
    if (profile_) tag_ = std::move(t);
  }

  // Encodes `name` over n threads (1-D grid). Arguments bind to buffer indices 0, 1, ... in order:
  // a View binds a buffer, an int / unsigned / float is copied with setBytes.
  template <typename... Args>
  void run(const char* name, long long n, const Args&... args) {
    if (n <= 0) return;
    if (n > UINT_MAX) fail("grid too large");
    @autoreleasepool {
      id<MTLComputePipelineState> pipeline = this->pipeline(name);
      id<MTLComputeCommandEncoder> enc = encoder();
      [enc setComputePipelineState:pipeline];
      NSUInteger index = 0;
      (bind(enc, index++, args), ...);
      NSUInteger group = std::min<NSUInteger>(256, pipeline.maxTotalThreadsPerThreadgroup);
      [enc dispatchThreads:MTLSizeMake(static_cast<NSUInteger>(n), 1, 1) threadsPerThreadgroup:MTLSizeMake(group, 1, 1)];
    }
    if (profile_) {
      key_ = tag_.empty() ? std::string(name) : tag_ + "  " + name;
      if (std::strcmp(name, "k_image") == 0) ++frames_;
      sync();
    }
  }

  // Commits the open command buffer and waits for it. Afterwards the host may read and write any buffer.
  void sync() {
    if (!command_) return;
    id<MTLCommandBuffer> command = command_;
    [encoder_ endEncoding];
    command_ = nil;
    encoder_ = nil;
    [command commit];
    [command waitUntilCompleted];
    // Buffers released while the command buffer was open are now idle.
    free_.insert(pending_.begin(), pending_.end());
    pending_.clear();
    if (command.status == MTLCommandBufferStatusError) fail("command buffer failed: " + describe_error(command.error));
    if (profile_ && !key_.empty()) {
      Stat& st = stats_[key_];
      st.ms += (command.GPUEndTime - command.GPUStartTime) * 1e3;
      ++st.calls;
      key_.clear();
    }
  }

  // Pool of shared-storage buffers, reused by size. `host`: the caller writes the buffer from the host
  // before the GPU uses it, so it must not be in use by the open command buffer. Otherwise a buffer that
  // was released during the open command buffer can be reused at once: dispatches run in order.
  id<MTLBuffer> alloc(size_t bytes, bool host) {
    bytes = std::max<size_t>(bytes, 16);
    if (!host) {
      auto it = pending_.find(bytes);
      if (it != pending_.end()) {
        id<MTLBuffer> b = it->second;
        pending_.erase(it);
        return b;
      }
    }
    auto it = free_.find(bytes);
    if (it != free_.end()) {
      id<MTLBuffer> b = it->second;
      free_.erase(it);
      return b;
    }
    if (bytes > device_.maxBufferLength) fail("buffer of " + std::to_string(bytes) + " bytes exceeds the device limit");
    id<MTLBuffer> b = [device_ newBufferWithLength:bytes options:MTLResourceStorageModeShared];
    if (!b) {  // give back what is cached and try once more
      free_.clear();
      b = [device_ newBufferWithLength:bytes options:MTLResourceStorageModeShared];
      if (!b) fail("out of memory allocating " + std::to_string(bytes) + " bytes");
    }
    return b;
  }
  void release(id<MTLBuffer> b, size_t bytes) {
    bytes = std::max<size_t>(bytes, 16);
    (command_ ? pending_ : free_).emplace(bytes, b);
  }

  // Device copy of a weight tensor, made on first use. Weights outlive the backend (see jkp_ctx).
  View param(const Param& p) {
    auto it = params_.find(p.data);
    if (it != params_.end()) return {it->second, 0};
    size_t bytes = std::max<size_t>(p.size() * sizeof(float), 16);
    id<MTLBuffer> b = [device_ newBufferWithLength:bytes options:MTLResourceStorageModeShared];
    if (!b) fail("out of memory for weights");
    if (p.size()) std::memcpy([b contents], p.data, p.size() * sizeof(float));
    params_[p.data] = b;
    return {b, 0};
  }

 private:
  struct Stat {
    double ms = 0;
    long calls = 0;
  };

  void report() const {
    const double frames = std::max(1L, frames_);
    double total = 0;
    std::map<std::string, Stat> by_kernel;
    std::vector<std::pair<std::string, Stat>> rows(stats_.begin(), stats_.end());
    for (const auto& r : rows) {
      total += r.second.ms;
      std::string kernel = r.first.substr(r.first.rfind(' ') + 1);
      by_kernel[kernel].ms += r.second.ms;
      by_kernel[kernel].calls += r.second.calls;
    }
    auto print = [&](const char* title, std::vector<std::pair<std::string, Stat>> v) {
      std::sort(v.begin(), v.end(), [](const auto& a, const auto& b) { return a.second.ms > b.second.ms; });
      std::fprintf(stderr, "\n%-58s %10s %7s %6s\n", title, "ms/frame", "share", "calls");
      for (const auto& r : v)
        std::fprintf(stderr, "%-58s %10.3f %6.1f%% %6.1f\n", r.first.c_str(), r.second.ms / frames,
                     total > 0 ? 100.0 * r.second.ms / total : 0.0, r.second.calls / frames);
    };
    std::fprintf(stderr, "\njkp metal profile: %ld frames, GPU time %.2f ms/frame\n", frames_, total / frames);
    print("operation  kernel", rows);
    print("kernel", std::vector<std::pair<std::string, Stat>>(by_kernel.begin(), by_kernel.end()));
  }

  static void bind(id<MTLComputeCommandEncoder> enc, NSUInteger i, const View& v) {
    [enc setBuffer:v.buffer offset:v.offset atIndex:i];
  }
  static void bind(id<MTLComputeCommandEncoder> enc, NSUInteger i, int v) { [enc setBytes:&v length:sizeof(v) atIndex:i]; }
  static void bind(id<MTLComputeCommandEncoder> enc, NSUInteger i, unsigned v) {
    [enc setBytes:&v length:sizeof(v) atIndex:i];
  }
  static void bind(id<MTLComputeCommandEncoder> enc, NSUInteger i, float v) {
    [enc setBytes:&v length:sizeof(v) atIndex:i];
  }

  id<MTLComputeCommandEncoder> encoder() {
    if (!command_) {
      command_ = [queue_ commandBuffer];
      if (!command_) fail("cannot create a command buffer");
      // Serial dispatch: each kernel sees the results of the previous ones.
      encoder_ = [command_ computeCommandEncoderWithDispatchType:MTLDispatchTypeSerial];
    }
    return encoder_;
  }

  id<MTLComputePipelineState> pipeline(const char* name) {
    auto it = pipelines_.find(name);
    if (it != pipelines_.end()) return it->second;
    id<MTLFunction> fn = [library_ newFunctionWithName:@(name)];
    if (!fn) fail(std::string("kernel ") + name + " not found");
    NSError* error = nil;
    id<MTLComputePipelineState> p = [device_ newComputePipelineStateWithFunction:fn error:&error];
    if (!p) fail(std::string("cannot create pipeline ") + name + ": " + describe_error(error));
    pipelines_[name] = p;
    return p;
  }

  id<MTLDevice> device_;
  id<MTLCommandQueue> queue_;
  id<MTLLibrary> library_;
  std::map<std::string, id<MTLComputePipelineState>> pipelines_;
  std::map<const float*, id<MTLBuffer>> params_;
  id<MTLCommandBuffer> command_ = nil;
  id<MTLComputeCommandEncoder> encoder_ = nil;
  std::multimap<size_t, id<MTLBuffer>> free_, pending_;
  bool profile_ = false;
  std::string tag_, key_;
  std::map<std::string, Stat> stats_;
  long frames_ = 0;
};
using ContextPtr = std::shared_ptr<Context>;

// A typed block from the pool, returned to it on destruction.
template <typename T>
class Buffer {
 public:
  Buffer(const ContextPtr& ctx, size_t n, bool host = false)
      : ctx_(ctx), n_(n), b_(ctx->alloc(n * sizeof(T), host)) {}
  ~Buffer() { ctx_->release(b_, n_ * sizeof(T)); }
  Buffer(const Buffer&) = delete;
  Buffer& operator=(const Buffer&) = delete;
  size_t size() const { return n_; }
  View view(size_t offset = 0) const { return {b_, offset * sizeof(T)}; }
  // Host access; valid for reading results after Context::sync, and for writing host buffers.
  T* host() const { return static_cast<T*>([b_ contents]); }

 private:
  ContextPtr ctx_;
  size_t n_;
  id<MTLBuffer> b_;
};

struct MetalTensor : Tensor {
  ContextPtr ctx;
  Buffer<float> buf;
  MetalTensor(const ContextPtr& ctx_, int c_, int h_, int w_)
      : ctx(ctx_), buf(ctx_, static_cast<size_t>(count(static_cast<long long>(c_) * h_ * w_))) {
    c = c_, h = h_, w = w_;
  }
  void read(float* dst) const override {
    ctx->sync();
    if (buf.size()) std::memcpy(dst, buf.host(), buf.size() * sizeof(float));
  }
  View d() const { return buf.view(); }
  int size() const { return static_cast<int>(buf.size()); }
};
using MetalPtr = std::shared_ptr<MetalTensor>;

const MetalTensor& dev(const TensorPtr& t) { return static_cast<const MetalTensor&>(*t); }

int act_id(Act act) { return act == Act::Selu ? kActSelu : act == Act::Sigmoid ? kActSigmoid : kActNone; }

class MetalOps : public Ops {
 public:
  explicit MetalOps(int device) : ctx_(std::make_shared<Context>(device)) {}

  TensorPtr image(const uint8_t* data, int width, int height, int stride, int channels) override {
    if (channels != 1 && channels != 3 && channels != 4) throw std::runtime_error("unsupported pixel format");
    if (stride == 0) stride = width * channels;
    MetalPtr out = make(3, height, width);
    // The last row may be shorter than the stride.
    size_t bytes = static_cast<size_t>(stride) * (height - 1) + static_cast<size_t>(width) * channels;
    ctx_->tag(format("image %dx%d", width, height));
    Buffer<uint8_t> src(ctx_, bytes, true);
    std::memcpy(src.host(), data, bytes);
    ctx_->run("k_image", out->size(), src.view(), stride, channels, width, height, out->d());
    return out;
  }

  TensorPtr pad_replicate(const TensorPtr& xp, int left, int right, int top, int bottom) override {
    const MetalTensor& x = dev(xp);
    MetalPtr out = make(x.c, x.h + top + bottom, x.w + left + right);
    ctx_->tag(format("pad %dx%d", out->w, out->h));
    ctx_->run("k_pad_replicate", out->size(), x.d(), x.c, x.h, x.w, left, top, out->h, out->w, out->d());
    return out;
  }

  TensorPtr crop(const TensorPtr& xp, int left, int top, int width, int height) override {
    const MetalTensor& x = dev(xp);
    if (left == 0 && top == 0 && width == x.w && height == x.h) return xp;  // tensors are never modified
    MetalPtr out = make(x.c, height, width);
    ctx_->tag(format("crop c%d %dx%d", x.c, width, height));
    ctx_->run("k_crop", out->size(), x.d(), x.c, x.h, x.w, left, top, height, width, out->d());
    return out;
  }

  TensorPtr conv2d(const TensorPtr& xp, const Param& weight, const Param* bias, Act act) override {
    const MetalTensor& x = dev(xp);
    const int cout = weight.shape[0], cin = weight.shape[1], k = weight.shape[2];
    if (cin != x.c || weight.shape[3] != k || k % 2 == 0) throw std::runtime_error("conv2d: shape mismatch");
    MetalPtr out = make(cout, x.h, x.w);
    ctx_->tag(format("conv%dx%d %3d->%-3d %4dx%-4d", k, k, cin, cout, x.w, x.h));
    View w = ctx_->param(weight), b = bias ? ctx_->param(*bias) : w;
    if (k == 1 || k == 3) {
      const int t = tile(cout);
      const long long threads = static_cast<long long>((cout + t - 1) / t) * x.h * x.w;
      ctx_->run(format("k_conv2d_t%d_k%d", t, k).c_str(), threads, x.d(), w, b, bias ? 1 : 0, cin, cout, x.h, x.w,
                act_id(act), out->d());
    } else {
      ctx_->run("k_conv2d", out->size(), x.d(), w, b, bias ? 1 : 0, cin, cout, x.h, x.w, k, act_id(act), out->d());
    }
    return out;
  }

  TensorPtr deform_conv2d(const TensorPtr& xp, const Param& offset_weight, const Param& offset_bias,
                          const Param& weight, const Param& bias, Act act) override {
    const MetalTensor& x = dev(xp);
    const int cout = weight.shape[0], cin = weight.shape[1], h = x.h, w = x.w, hw = h * w;
    if (cin != x.c || weight.shape[2] != 3 || weight.shape[3] != 3 || offset_weight.shape[0] != 18)
      throw std::runtime_error("deform_conv2d: shape mismatch");
    TensorPtr offset = conv2d(xp, offset_weight, &offset_bias, Act::None);
    const float max_offset = static_cast<float>(std::max(h, w)) / 4.0f;
    ctx_->tag(format("deform  %3d->%-3d %4dx%-4d", cin, cout, w, h));
    Buffer<float> col(ctx_, static_cast<size_t>(count(static_cast<long long>(cin) * 9 * hw)));
    ctx_->run("k_deform_sample", 9LL * hw, x.d(), dev(offset).d(), cin, h, w, max_offset, col.view());
    MetalPtr out = make(cout, h, w);
    const int t = tile(cout);
    ctx_->run(format("k_deform_sum_t%d", t).c_str(), static_cast<long long>((cout + t - 1) / t) * hw, col.view(),
              ctx_->param(weight), ctx_->param(bias), cin * 9, cout, hw, act_id(act), out->d());
    return out;
  }

  TensorPtr add(const TensorPtr& ap, const TensorPtr& bp, Act act) override {
    const MetalTensor &a = dev(ap), &b = dev(bp);
    if (a.size() != b.size()) throw std::runtime_error("add: shape mismatch");
    MetalPtr out = make(a.c, a.h, a.w);
    ctx_->tag(format("add c%d %dx%d", a.c, a.w, a.h));
    ctx_->run("k_add", out->size(), a.d(), b.d(), out->size(), act_id(act), out->d());
    return out;
  }

  TensorPtr avg_pool(const TensorPtr& xp, int k) override {
    const MetalTensor& x = dev(xp);
    if (k < 1 || x.h % k || x.w % k) throw std::runtime_error("avg_pool: size is not a multiple of the window");
    MetalPtr out = make(x.c, x.h / k, x.w / k);
    ctx_->tag(format("avg_pool%d c%d %dx%d", k, x.c, x.w, x.h));
    ctx_->run("k_avg_pool", out->size(), x.d(), x.c, x.w, out->h, out->w, k, out->d());
    return out;
  }

  TensorPtr upsample(const TensorPtr& xp, int scale) override {
    const MetalTensor& x = dev(xp);
    MetalPtr out = make(x.c, x.h * scale, x.w * scale);
    ctx_->tag(format("upsample%d c%d -> %dx%d", scale, x.c, out->w, out->h));
    auto ratio = [](int in, int outn) {
      return outn > 1 ? static_cast<float>(in - 1) / static_cast<float>(outn - 1) : 0.0f;
    };
    ctx_->run("k_upsample", out->size(), x.d(), x.c, x.h, x.w, out->h, out->w, ratio(x.w, out->w), ratio(x.h, out->h),
              out->d());
    return out;
  }

  TensorPtr concat(const std::vector<TensorPtr>& xs) override {
    int c = 0;
    for (const auto& t : xs) {
      if (t->h != xs[0]->h || t->w != xs[0]->w) throw std::runtime_error("concat: shape mismatch");
      c += t->c;
    }
    MetalPtr out = make(c, xs[0]->h, xs[0]->w);
    ctx_->tag(format("concat c%d %dx%d", c, out->w, out->h));
    size_t pos = 0;
    for (const auto& t : xs) {
      const MetalTensor& x = dev(t);
      ctx_->run("k_copy", x.size(), x.d(), x.size(), out->buf.view(pos));
      pos += x.size();
    }
    return out;
  }

  TensorPtr l2_normalize(const TensorPtr& xp) override {
    const MetalTensor& x = dev(xp);
    MetalPtr out = make(x.c, x.h, x.w);
    ctx_->tag(format("l2_normalize c%d %dx%d", x.c, x.w, x.h));
    ctx_->run("k_l2_normalize", x.h * x.w, x.d(), x.c, x.h * x.w, out->d());
    return out;
  }

  // The upsampled parts are written straight into their slice of the output; parts at scale 1 are copied.
  TensorPtr upsample_concat(const std::vector<TensorPtr>& xs, const std::vector<int>& scales) override {
    if (xs.empty() || xs.size() != scales.size()) throw std::runtime_error("upsample_concat: bad arguments");
    const int oh = xs[0]->h * scales[0], ow = xs[0]->w * scales[0];
    int c = 0;
    for (size_t i = 0; i < xs.size(); ++i) {
      if (xs[i]->h * scales[i] != oh || xs[i]->w * scales[i] != ow) throw std::runtime_error("concat: shape mismatch");
      c += xs[i]->c;
    }
    MetalPtr out = make(c, oh, ow);
    auto ratio = [](int in, int outn) {
      return outn > 1 ? static_cast<float>(in - 1) / static_cast<float>(outn - 1) : 0.0f;
    };
    size_t pos = 0;
    for (size_t i = 0; i < xs.size(); ++i) {
      const MetalTensor& x = dev(xs[i]);
      const int n = x.c * oh * ow;
      if (scales[i] == 1) {
        ctx_->tag(format("concat c%d %dx%d", x.c, ow, oh));
        ctx_->run("k_copy", n, x.d(), n, out->buf.view(pos));
      } else {
        ctx_->tag(format("upsample%d c%d -> %dx%d", scales[i], x.c, ow, oh));
        ctx_->run("k_upsample", n, x.d(), x.c, x.h, x.w, oh, ow, ratio(x.w, ow), ratio(x.h, oh), out->buf.view(pos));
      }
      pos += static_cast<size_t>(n);
    }
    return out;
  }

  TensorPtr l2_normalize_crop(const TensorPtr& xp, int left, int top, int width, int height) override {
    const MetalTensor& x = dev(xp);
    MetalPtr out = make(x.c, height, width);
    ctx_->tag(format("l2_normalize_crop c%d %dx%d", x.c, width, height));
    ctx_->run("k_l2_normalize_crop", width * height, x.d(), x.c, x.h, x.w, left, top, height, width, out->d());
    return out;
  }

  void detect(const TensorPtr& score_map, const DetectParams& params, Keypoints* out) override {
    const MetalTensor& sm = dev(score_map);
    const int w = sm.w, h = sm.h, n = w * h;
    const View s = sm.d();
    out->xy_norm.clear();
    out->score.clear();
    if (n == 0) return;
    ctx_->tag(format("detect %dx%d", w, h));

    // Non-maximum suppression (simple_nms from SuperGlue, two refinement rounds).
    Buffer<float> nms(ctx_, n);
    {
      Buffer<float> tmp(ctx_, n), mask(ctx_, n), pooled_mask(ctx_, n), supp(ctx_, n), pooled_supp(ctx_, n);
      auto max_filter = [&](const View& src, const View& dst) {
        ctx_->run("k_max_filter", n, src, w, h, kRadius, 0, tmp.view());
        ctx_->run("k_max_filter", n, tmp.view(), w, h, kRadius, 1, dst);
      };
      max_filter(s, pooled_supp.view());
      ctx_->run("k_nms_init", n, s, pooled_supp.view(), n, mask.view());
      for (int round = 0; round < 2; ++round) {
        max_filter(mask.view(), pooled_mask.view());
        ctx_->run("k_nms_suppress", n, s, pooled_mask.view(), n, supp.view());
        max_filter(supp.view(), pooled_supp.view());
        ctx_->run("k_nms_update", n, supp.view(), pooled_supp.view(), pooled_mask.view(), n, mask.view());
      }
      ctx_->run("k_nms_final", n, s, mask.view(), w, h, kRadius, nms.view());
    }

    // Selection, on the device. `idx` receives the pixel indices of the keypoints in output order.
    const int blocks = (n + kScanBlock - 1) / kScanBlock;
    Buffer<unsigned> offsets(ctx_, static_cast<size_t>(blocks) + 1, true);
    // Counts {nms `mode` th} and leaves the per-block offsets (exclusive prefix sum, on the host) in `offsets`.
    auto select_count = [&](int mode, float th) {
      ctx_->run("k_select_count", blocks, nms.view(), n, mode, th, offsets.view());
      ctx_->sync();
      unsigned* o = offsets.host();
      unsigned sum = 0;
      for (int b = 0; b < blocks; ++b) {
        unsigned c = o[b];
        o[b] = sum;
        sum += c;
      }
      o[blocks] = sum;
      return static_cast<int>(sum);
    };
    // Writes the first `limit` of that set in raster order; must follow the matching select_count.
    auto select_write = [&](int mode, float th, int limit, const View& dst) {
      ctx_->run("k_select_write", blocks, nms.view(), n, mode, th, offsets.view(), static_cast<unsigned>(limit), dst);
    };

    int kept = 0;         // number of keypoints
    int best = -1;        // >= 0: keep the `best` highest scores, best first
    float threshold = 0;  // otherwise: keep nms > threshold, in raster order
    if (params.top_k > 0) {
      best = std::min(params.top_k, n);
    } else {
      int passing = params.scores_th > 0 ? select_count(kGreater, threshold = params.scores_th) : 0;
      if (passing == 0) {  // fall back to the mean score, summed in raster order like the CPU backend
        ctx_->sync();
        const float* v = sm.buf.host();
        float total = 0;
        for (int i = 0; i < n; ++i) total += v[i];
        passing = select_count(kGreater, threshold = total / static_cast<float>(n));
      }
      if (passing > params.n_limit) best = std::max(0, params.n_limit);
      else kept = passing;
    }
    if (best >= 0) kept = best;
    if (kept == 0) return;

    Buffer<int> idx(ctx_, kept);
    if (best < 0) {
      select_write(kGreater, threshold, kept, idx.view());
    } else {
      // Radix select for the value of the `best`-th highest score, one byte of the float bits per pass.
      Buffer<unsigned> hist(ctx_, 256, true);
      unsigned prefix = 0, mask = 0;
      int remaining = best;  // how many are still needed from the values matching the prefix
      for (int shift = 24; shift >= 0; shift -= 8) {
        std::memset(hist.host(), 0, 256 * sizeof(unsigned));  // idle: the previous pass synced
        ctx_->run("k_histogram", n, nms.view(), n, mask, prefix, shift, hist.view());
        ctx_->sync();
        const unsigned* hv = hist.host();
        int bin = 255;
        for (; bin > 0 && static_cast<long long>(hv[bin]) < remaining; --bin) remaining -= static_cast<int>(hv[bin]);
        prefix |= static_cast<unsigned>(bin) << shift;
        mask |= 255u << shift;
      }
      float kth;
      std::memcpy(&kth, &prefix, sizeof(kth));
      // Everything above that value, then the first `remaining` equal to it in raster order.
      const int above = best - remaining;
      Buffer<int> unsorted(ctx_, kept);
      if (select_count(kGreater, kth) != above) fail("top-k selection is inconsistent");
      select_write(kGreater, kth, above, unsorted.view());
      select_count(kEqual, kth);
      select_write(kEqual, kth, remaining, unsorted.view(above));
      ctx_->run("k_rank_sort", kept, nms.view(), unsorted.view(), kept, idx.view());
    }

    // Refinement and readback of the kept keypoints only.
    Buffer<float> xy(ctx_, 2 * static_cast<size_t>(kept)), score(ctx_, kept);
    ctx_->run("k_refine", kept, s, w, h, idx.view(), kept, xy.view(), score.view());
    ctx_->sync();
    out->xy_norm.assign(xy.host(), xy.host() + 2 * static_cast<size_t>(kept));
    out->score.assign(score.host(), score.host() + kept);
  }

  void describe(const TensorPtr& feature_map, const Keypoints& kpts, const SddhParams& p,
                std::vector<float>* desc) override {
    const MetalTensor& f = dev(feature_map);
    const int c = f.c, h = f.h, w = f.w, total = kpts.n(), K = p.kernel, M = p.positions;
    const int dim = p.agg_w->shape[2];
    if (p.offset0_w->shape[1] != c || p.agg_w->shape[1] != c || p.sf_w->shape[0] != c)
      throw std::runtime_error("describe: shape mismatch");
    const float max_offset = static_cast<float>(std::max(h, w)) / 4.0f;
    desc->assign(static_cast<size_t>(total) * dim, 0.0f);
    ctx_->tag("describe");

    // In chunks, so the per-keypoint work buffers (M*C floats each) stay small for any keypoint count.
    const int chunk = 8192;
    for (int begin = 0; begin < total; begin += chunk) {
      const int n = std::min(chunk, total - begin);
      const long long samples = static_cast<long long>(n) * M * c;
      Buffer<float> xy(ctx_, 2 * static_cast<size_t>(n), true), o0(ctx_, static_cast<size_t>(n) * 2 * M),
          o1(ctx_, static_cast<size_t>(n) * 2 * M), sampled(ctx_, samples), feat(ctx_, samples),
          d(ctx_, static_cast<size_t>(n) * dim);
      std::memcpy(xy.host(), kpts.xy_norm.data() + 2 * static_cast<size_t>(begin), xy.size() * sizeof(float));
      ctx_->run("k_sddh_offset0", n * 2 * M, f.d(), c, h, w, xy.view(), n, K, ctx_->param(*p.offset0_w),
                ctx_->param(*p.offset0_b), 2 * M, o0.view());
      ctx_->run("k_sddh_offset1", n * 2 * M, o0.view(), n, 2 * M, ctx_->param(*p.offset1_w), ctx_->param(*p.offset1_b),
                max_offset, o1.view());
      ctx_->run("k_sddh_sample", n * M, f.d(), c, h, w, xy.view(), o1.view(), n, M, sampled.view());
      ctx_->run("k_sddh_sf", samples, sampled.view(), count(samples), c, ctx_->param(*p.sf_w), feat.view());
      ctx_->run("k_sddh_aggregate", n * dim, feat.view(), n, M * c, dim, ctx_->param(*p.agg_w), d.view());
      ctx_->run("k_normalize_rows", n, d.view(), n, dim);
      ctx_->sync();
      std::memcpy(desc->data() + static_cast<size_t>(begin) * dim, d.host(), d.size() * sizeof(float));
    }
  }

 private:
  // Output channels per thread for the tiled convolution kernels (instantiated for 4, 8, 16, 32).
  static int tile(int cout) {
    static const int forced = [] {
      const char* env = std::getenv("JKP_METAL_TILE");  // tuning aid
      return env ? std::atoi(env) : 0;
    }();
    if (forced == 4 || forced == 8 || forced == 16 || forced == 32) return forced;
    return cout <= 4 ? 4 : cout <= 8 ? 8 : 16;
  }

  MetalPtr make(int c, int h, int w) { return std::make_shared<MetalTensor>(ctx_, c, h, w); }

  ContextPtr ctx_;
};

