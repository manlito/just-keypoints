    Buffer<float> desc(ctx_, static_cast<size_t>(kept) * dim), s(ctx_, kept);
    ctx_->run("k_xfeat_describe", static_cast<long long>(kept) * dim, f.d(), dim, h8, w8, score.view(), idx.view(), kept,
              desc.view(), s.view(), pix.view());
    ctx_->run("k_normalize_rows", kept, desc.view(), kept, dim);
    ctx_->sync();
    out->pix.assign(pix.host(), pix.host() + 2 * static_cast<size_t>(kept));
    out->score.assign(s.host(), s.host() + kept);
    out->desc.assign(desc.host(), desc.host() + static_cast<size_t>(kept) * dim);
  }

  void describe(const TensorPtr& feature_map, const Keypoints& kpts, const SddhParams& p,
