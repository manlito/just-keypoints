[[noreturn]] void fail(const std::string& what) { throw std::runtime_error("metal: " + what); }

std::string format(const char* fmt, ...) {
  char buf[160];
  va_list args;
  va_start(args, fmt);
  std::vsnprintf(buf, sizeof(buf), fmt, args);
  va_end(args);
  return buf;
}

std::string describe_error(NSError* error) {
  return error ? std::string([[error localizedDescription] UTF8String]) : std::string("unknown error");
}

// Element count as int; the kernels index with 32-bit integers.
int count(long long n) {
  if (n < 0 || n > INT_MAX) fail("tensor too large");
  return static_cast<int>(n);
}

// A buffer bound to a kernel argument, at a byte offset.
struct View {
  id<MTLBuffer> buffer;
  size_t offset = 0;
};

// Mirrors PyramidArgs in kernels.metal.
struct PyramidArgs {
  int c[4] = {0, 0, 0, 0}, h[4] = {1, 1, 1, 1}, w[4] = {1, 1, 1, 1}, scale[4] = {1, 1, 1, 1};
  float sx[4] = {0, 0, 0, 0}, sy[4] = {0, 0, 0, 0};
  int H = 0, W = 0;
  int left = 0, top = 0;
};

// Device, queue, compiled kernels, the open command buffer and the buffer pool. Shared by the backend
// and every tensor it created, so a tensor can flush pending work before it is read.
class Context {
 public:
  Context(int index, bool fp16) : fp16_(fp16) {
    const char* env = std::getenv("JKP_METAL_PROFILE");
    profile_ = env && *env && std::string(env) != "0";
    @autoreleasepool {
      NSArray<id<MTLDevice>>* devices = MTLCopyAllDevices();
      if (devices.count == 0) fail("no Metal device found");
      if (index < 0 || index >= static_cast<int>(devices.count))
        fail("device " + std::to_string(index) + " not found (" + std::to_string(devices.count) + " available)");
      device_ = devices[index];
      queue_ = [device_ newCommandQueue];
      if (!queue_) fail("cannot create a command queue");

      MTLCompileOptions* options = [[MTLCompileOptions alloc] init];
      if (@available(macOS 15.0, iOS 18.0, *)) {
        options.mathMode = MTLMathModeSafe;
        options.mathFloatingPointFunctions = MTLMathFloatingPointFunctionsPrecise;
      } else {
#pragma clang diagnostic push
#pragma clang diagnostic ignored "-Wdeprecated-declarations"
        options.fastMathEnabled = NO;
#pragma clang diagnostic pop
      }
      if (fp16_) options.preprocessorMacros = @{@"JKP_FP16" : @1};
      NSError* error = nil;
      library_ = [device_ newLibraryWithSource:@(kJkpMetalSource) options:options error:&error];
      if (!library_) fail("shader compilation failed: " + describe_error(error));
    }
  }

  ~Context() {
    try {
      sync();
    } catch (...) {
    }
    if (profile_) report();
  }

  // Profiling label for the dispatches that follow (the operation and its shape).
  void tag(std::string t) {
    if (profile_) tag_ = std::move(t);
  }

  // Encodes `name` over n threads (1-D grid). Arguments bind to buffer indices 0, 1, ... in order:
  // a View binds a buffer, an int / unsigned / float is copied with setBytes.
  template <typename... Args>
  void run(const char* name, long long n, const Args&... args) {
    if (n <= 0) return;
    if (n > UINT_MAX) fail("grid too large");
    @autoreleasepool {
      id<MTLComputePipelineState> pipeline = this->pipeline(name);
      id<MTLComputeCommandEncoder> enc = encoder();
      [enc setComputePipelineState:pipeline];
      NSUInteger index = 0;
      (bind(enc, index++, args), ...);
      NSUInteger group = std::min<NSUInteger>(256, pipeline.maxTotalThreadsPerThreadgroup);
      [enc dispatchThreads:MTLSizeMake(static_cast<NSUInteger>(n), 1, 1) threadsPerThreadgroup:MTLSizeMake(group, 1, 1)];
    }
    if (profile_) {
      key_ = tag_.empty() ? std::string(name) : tag_ + "  " + name;
      if (std::strcmp(name, "k_image") == 0) ++frames_;
      sync();
    }
  }

  // Commits the open command buffer and waits for it. Afterwards the host may read and write any buffer.
  void sync() {
    if (!command_) return;
    id<MTLCommandBuffer> command = command_;
    [encoder_ endEncoding];
    command_ = nil;
    encoder_ = nil;
    [command commit];
    [command waitUntilCompleted];
    // Buffers released while the command buffer was open are now idle.
    free_.insert(pending_.begin(), pending_.end());
    pending_.clear();
    if (command.status == MTLCommandBufferStatusError) fail("command buffer failed: " + describe_error(command.error));
    if (profile_ && !key_.empty()) {
      Stat& st = stats_[key_];
      st.ms += (command.GPUEndTime - command.GPUStartTime) * 1e3;
      ++st.calls;
      key_.clear();
    }
  }

  // Pool of shared-storage buffers, reused by size. `host`: the caller writes the buffer from the host
  // before the GPU uses it, so it must not be in use by the open command buffer. Otherwise a buffer that
  // was released during the open command buffer can be reused at once: dispatches run in order.
  id<MTLBuffer> alloc(size_t bytes, bool host) {
    bytes = std::max<size_t>(bytes, 16);
    if (!host) {
      auto it = pending_.find(bytes);
      if (it != pending_.end()) {
        id<MTLBuffer> b = it->second;
        pending_.erase(it);
        return b;
      }
    }
    auto it = free_.find(bytes);
    if (it != free_.end()) {
      id<MTLBuffer> b = it->second;
      free_.erase(it);
      return b;
    }
    if (bytes > device_.maxBufferLength) fail("buffer of " + std::to_string(bytes) + " bytes exceeds the device limit");
    id<MTLBuffer> b = [device_ newBufferWithLength:bytes options:MTLResourceStorageModeShared];
    if (!b) {  // give back what is cached and try once more
      free_.clear();
      b = [device_ newBufferWithLength:bytes options:MTLResourceStorageModeShared];
      if (!b) fail("out of memory allocating " + std::to_string(bytes) + " bytes");
    }
    return b;
  }
  void release(id<MTLBuffer> b, size_t bytes) {
    bytes = std::max<size_t>(bytes, 16);
    (command_ ? pending_ : free_).emplace(bytes, b);
  }

  bool fp16() const { return fp16_; }

  // Device copy of a weight tensor, made on first use and cached by its host address, so weights must stay
  // alive and unchanged for the backend's lifetime (see jkp_ctx).
  // param: in the kernels' storage type (`real`); param_f32: always float.
  View param(const Param& p) { return param(p, fp16_); }
  View param_f32(const Param& p) { return param(p, false); }
  // Weights [cout][taps] of a tiled kernel in tap-major order, cout padded with zeros to a multiple of
  // `tile`: w[tap * cpad + oc] (see kernels.metal). In the kernels' storage type, or float with `f32`.
  View param_tiled(const Param& p, int tile, bool f32 = false) {
    const bool half = fp16_ && !f32;
    auto key = std::make_pair(p.data, half ? tile : -tile);
    auto it = params_tiled_.find(key);
    if (it != params_tiled_.end()) return {it->second, 0};
    const size_t cout = static_cast<size_t>(p.shape[0]), taps = cout ? p.size() / cout : 0;
    const size_t cpad = (cout + tile - 1) / tile * tile, n = taps * cpad;
    const size_t elem = half ? sizeof(uint16_t) : sizeof(float);
    id<MTLBuffer> b = [device_ newBufferWithLength:std::max<size_t>(n * elem, 16) options:MTLResourceStorageModeShared];
    if (!b) fail("out of memory for weights");
    std::memset([b contents], 0, n * elem);
    for (size_t oc = 0; oc < cout; ++oc)
      for (size_t t = 0; t < taps; ++t) {
        const float v = p.data[oc * taps + t];
        if (half) static_cast<uint16_t*>([b contents])[t * cpad + oc] = float_to_half(v);
        else static_cast<float*>([b contents])[t * cpad + oc] = v;
      }
    params_tiled_[key] = b;
    return {b, 0};
  }

 private:
  View param(const Param& p, bool half) {
    auto& cache = half ? params_half_ : params_;
    auto it = cache.find(p.data);
    if (it != cache.end()) return {it->second, 0};
    const size_t elem = half ? sizeof(uint16_t) : sizeof(float);
    id<MTLBuffer> b = [device_ newBufferWithLength:std::max<size_t>(p.size() * elem, 16)
                                           options:MTLResourceStorageModeShared];
    if (!b) fail("out of memory for weights");
    if (half) {
      uint16_t* dst = static_cast<uint16_t*>([b contents]);
      for (size_t i = 0; i < p.size(); ++i) dst[i] = float_to_half(p.data[i]);
    } else if (p.size()) {
      std::memcpy([b contents], p.data, p.size() * sizeof(float));
    }
    cache[p.data] = b;
    return {b, 0};
  }

  struct Stat {
    double ms = 0;
    long calls = 0;
  };

  void report() const {
    const double frames = std::max(1L, frames_);
    double total = 0;
    std::map<std::string, Stat> by_kernel;
    std::vector<std::pair<std::string, Stat>> rows(stats_.begin(), stats_.end());
    for (const auto& r : rows) {
      total += r.second.ms;
      std::string kernel = r.first.substr(r.first.rfind(' ') + 1);
      by_kernel[kernel].ms += r.second.ms;
      by_kernel[kernel].calls += r.second.calls;
    }
    auto print = [&](const char* title, std::vector<std::pair<std::string, Stat>> v) {
      std::sort(v.begin(), v.end(), [](const auto& a, const auto& b) { return a.second.ms > b.second.ms; });
      std::fprintf(stderr, "\n%-58s %10s %7s %6s\n", title, "ms/frame", "share", "calls");
      for (const auto& r : v)
        std::fprintf(stderr, "%-58s %10.3f %6.1f%% %6.1f\n", r.first.c_str(), r.second.ms / frames,
                     total > 0 ? 100.0 * r.second.ms / total : 0.0, r.second.calls / frames);
    };
    std::fprintf(stderr, "\njkp metal profile: %ld frames, GPU time %.2f ms/frame\n", frames_, total / frames);
    print("operation  kernel", rows);
    print("kernel", std::vector<std::pair<std::string, Stat>>(by_kernel.begin(), by_kernel.end()));
  }

  static void bind(id<MTLComputeCommandEncoder> enc, NSUInteger i, const View& v) {
    [enc setBuffer:v.buffer offset:v.offset atIndex:i];
  }
  static void bind(id<MTLComputeCommandEncoder> enc, NSUInteger i, int v) { [enc setBytes:&v length:sizeof(v) atIndex:i]; }
  static void bind(id<MTLComputeCommandEncoder> enc, NSUInteger i, unsigned v) {
    [enc setBytes:&v length:sizeof(v) atIndex:i];
  }
  static void bind(id<MTLComputeCommandEncoder> enc, NSUInteger i, float v) {
    [enc setBytes:&v length:sizeof(v) atIndex:i];
  }
  static void bind(id<MTLComputeCommandEncoder> enc, NSUInteger i, const PyramidArgs& v) {
    [enc setBytes:&v length:sizeof(v) atIndex:i];
  }

  id<MTLComputeCommandEncoder> encoder() {
    if (!command_) {
      command_ = [queue_ commandBuffer];
      if (!command_) fail("cannot create a command buffer");
      // Serial dispatch: each kernel sees the results of the previous ones.
      encoder_ = [command_ computeCommandEncoderWithDispatchType:MTLDispatchTypeSerial];
    }
    return encoder_;
  }

  id<MTLComputePipelineState> pipeline(const char* name) {
    auto it = pipelines_.find(name);
    if (it != pipelines_.end()) return it->second;
    id<MTLFunction> fn = [library_ newFunctionWithName:@(name)];
    if (!fn) fail(std::string("kernel ") + name + " not found");
    NSError* error = nil;
    id<MTLComputePipelineState> p = [device_ newComputePipelineStateWithFunction:fn error:&error];
    if (!p) fail(std::string("cannot create pipeline ") + name + ": " + describe_error(error));
    pipelines_[name] = p;
    return p;
  }

  id<MTLDevice> device_;
  id<MTLCommandQueue> queue_;
  id<MTLLibrary> library_;
  std::map<std::string, id<MTLComputePipelineState>> pipelines_;
  std::map<const float*, id<MTLBuffer>> params_, params_half_;
  std::map<std::pair<const float*, int>, id<MTLBuffer>> params_tiled_;
  bool fp16_ = false;
  id<MTLCommandBuffer> command_ = nil;
  id<MTLComputeCommandEncoder> encoder_ = nil;
  std::multimap<size_t, id<MTLBuffer>> free_, pending_;
  bool profile_ = false;
  std::string tag_, key_;
  std::map<std::string, Stat> stats_;
  long frames_ = 0;
};
using ContextPtr = std::shared_ptr<Context>;

// A typed block from the pool, returned to it on destruction.
template <typename T>
class Buffer {
 public:
  Buffer(const ContextPtr& ctx, size_t n, bool host = false)
      : ctx_(ctx), n_(n), b_(ctx->alloc(n * sizeof(T), host)) {}
  ~Buffer() { ctx_->release(b_, n_ * sizeof(T)); }
  Buffer(const Buffer&) = delete;
  Buffer& operator=(const Buffer&) = delete;
  size_t size() const { return n_; }
  View view(size_t offset = 0) const { return {b_, offset * sizeof(T)}; }
  // Host access; valid for reading results after Context::sync, and for writing host buffers.
  T* host() const { return static_cast<T*>([b_ contents]); }

 private:
  ContextPtr ctx_;
  size_t n_;
  id<MTLBuffer> b_;
};

// Ordered selection on a map of n non-negative floats, on the device. Counting is a round trip to the host,
// which computes the per-block offsets (exclusive prefix sum) in shared memory.
class Selection {
 public:
  Selection(const ContextPtr& ctx, const View& v, int n)
      : ctx_(ctx), v_(v), n_(n), blocks_((n + kScanBlock - 1) / kScanBlock), offsets_(ctx, static_cast<size_t>(blocks_) + 1, true) {}

  // Number of {v `mode` th}; leaves the per-block offsets for write().
  int count(int mode, float th) {
    ctx_->run("k_select_count", blocks_, v_, n_, mode, th, offsets_.view());
    ctx_->sync();
    unsigned* o = offsets_.host();
    unsigned sum = 0;
    for (int b = 0; b < blocks_; ++b) {
      unsigned c = o[b];
      o[b] = sum;
      sum += c;
    }
    o[blocks_] = sum;
    return static_cast<int>(sum);
  }
  // Writes the first `limit` of that set in raster order; must follow the matching count().
  void write(int mode, float th, int limit, const View& dst) {
    ctx_->run("k_select_write", blocks_, v_, n_, mode, th, offsets_.view(), static_cast<unsigned>(limit), dst);
  }
  // Indices of the `best` (<= n) highest values, best first, ties in raster order.
  void top(int best, const View& dst) {
    // Radix select for the value of the `best`-th highest, 16 bits of the float bits per pass (each pass
    // is a round trip to the host).
    const int bins = 65536;
    Buffer<unsigned> hist(ctx_, bins, true);
    unsigned prefix = 0, mask = 0;
    int remaining = best;  // how many are still needed from the values matching the prefix
    for (int shift = 16; shift >= 0; shift -= 16) {
      std::memset(hist.host(), 0, bins * sizeof(unsigned));  // idle: the previous pass synced
      ctx_->run("k_histogram", n_, v_, n_, mask, prefix, shift, hist.view());
      ctx_->sync();
      const unsigned* hv = hist.host();
      int bin = bins - 1;
      for (; bin > 0 && static_cast<long long>(hv[bin]) < remaining; --bin) remaining -= static_cast<int>(hv[bin]);
      prefix |= static_cast<unsigned>(bin) << shift;
      mask |= 65535u << shift;
    }
    float kth;
    std::memcpy(&kth, &prefix, sizeof(kth));
    // Everything above that value, then the first `remaining` equal to it in raster order.
    const int above = best - remaining;
    Buffer<int> unsorted(ctx_, best);
    if (count(kGreater, kth) != above) fail("top-k selection is inconsistent");
    write(kGreater, kth, above, unsorted.view());
    count(kEqual, kth);
    write(kEqual, kth, remaining, unsorted.view(above));
    ctx_->run("k_rank_sort", best, v_, unsorted.view(), best, dst);
  }

 private:
  ContextPtr ctx_;
  View v_;
  int n_, blocks_;
  Buffer<unsigned> offsets_;
};

struct MetalTensor;
using MetalPtr = std::shared_ptr<MetalTensor>;

// concat of parts[i] upsampled by scales[i]; with `normalized`, L2-normalized across channels and
// cropped to the tensor's size at (left, top).
struct Pyramid {
  std::vector<MetalPtr> parts;
  std::vector<int> scales;
  int height = 0, width = 0;  // full resolution
  bool normalized = false;
  int left = 0, top = 0;
};

// Elements are float, or half when the backend runs in FP16 and the tensor is not the score map.
// A tensor with a pyramid has no storage until d() or read() asks for it.
struct MetalTensor : Tensor {
  ContextPtr ctx;
  bool half;
  int n;
  std::shared_ptr<const Pyramid> pyramid;
  MetalTensor(const ContextPtr& ctx_, int c_, int h_, int w_, bool half_, std::shared_ptr<const Pyramid> pyramid_ = {})
      : ctx(ctx_), half(half_), n(count(static_cast<long long>(c_) * h_ * w_)), pyramid(std::move(pyramid_)) {
    c = c_, h = h_, w = w_;
    if (!pyramid) buf_ = std::make_unique<Buffer<uint8_t>>(ctx, bytes(n));
  }
  void read(float* dst) const override {
    const uint8_t* values = host();
    ctx->sync();
    if (half) {
      const uint16_t* src = reinterpret_cast<const uint16_t*>(values);
      for (int i = 0; i < n; ++i) dst[i] = half_to_float(src[i]);
    } else if (n) {
      std::memcpy(dst, values, static_cast<size_t>(n) * sizeof(float));
    }
  }
  size_t bytes(size_t elements) const { return elements * (half ? sizeof(uint16_t) : sizeof(float)); }
  View d() const { return at(0); }
  // View starting at element `i`.
  View at(size_t i) const {
    store();
    return buf_->view(bytes(i));
  }
  // Host pointer; valid for reading after Context::sync.
  const uint8_t* host() const {
    store();
    return buf_->host();
  }
  int size() const { return n; }
  PyramidArgs pyramid_args() const;

 private:
  void store() const;  // computes and stores the values of a pyramid tensor on first use
  mutable std::unique_ptr<Buffer<uint8_t>> buf_;
};

float upsample_ratio(int in, int out) { return out > 1 ? static_cast<float>(in - 1) / static_cast<float>(out - 1) : 0.0f; }

PyramidArgs MetalTensor::pyramid_args() const {
  PyramidArgs a;
  const Pyramid& p = *pyramid;
  for (size_t i = 0; i < p.parts.size(); ++i) {
    const MetalTensor& x = *p.parts[i];
    a.c[i] = x.c, a.h[i] = x.h, a.w[i] = x.w, a.scale[i] = p.scales[i];
    a.sx[i] = upsample_ratio(x.w, p.width), a.sy[i] = upsample_ratio(x.h, p.height);
  }
  a.H = p.height, a.W = p.width, a.left = p.left, a.top = p.top;
  return a;
}

void MetalTensor::store() const {
  if (buf_) return;
  const Pyramid& p = *pyramid;
  int channels = 0;
  for (const auto& x : p.parts) channels += x->c;
  const size_t plane = static_cast<size_t>(p.height) * p.width;
  // The concatenation, then (normalized form) normalization and crop into this tensor.
  auto out = std::make_unique<Buffer<uint8_t>>(ctx, bytes(p.normalized ? channels * plane : static_cast<size_t>(n)));
  size_t pos = 0;
  for (size_t i = 0; i < p.parts.size(); ++i) {
    const MetalTensor& x = *p.parts[i];
    const int count = x.c * p.height * p.width;
    if (p.scales[i] == 1) {
      ctx->tag(format("concat c%d %dx%d", x.c, p.width, p.height));
      ctx->run("k_copy", count, x.d(), count, out->view(bytes(pos)));
    } else {
      ctx->tag(format("upsample%d c%d -> %dx%d", p.scales[i], x.c, p.width, p.height));
      ctx->run("k_upsample", count, x.d(), x.c, x.h, x.w, p.height, p.width, upsample_ratio(x.w, p.width),
               upsample_ratio(x.h, p.height), out->view(bytes(pos)));
    }
    pos += static_cast<size_t>(count);
  }
  if (p.normalized) {
    auto cropped = std::make_unique<Buffer<uint8_t>>(ctx, bytes(n));
    ctx->tag(format("l2_normalize_crop c%d %dx%d", c, w, h));
    ctx->run("k_l2_normalize_crop", w * h, out->view(), c, p.height, p.width, p.left, p.top, h, w, cropped->view());
    out = std::move(cropped);
  }
  buf_ = std::move(out);
}


const MetalTensor& dev(const TensorPtr& t) { return static_cast<const MetalTensor&>(*t); }

int act_id(Act act) {
  switch (act) {
    case Act::None: return kActNone;
    case Act::Selu: return kActSelu;
    case Act::Sigmoid: return kActSigmoid;
    case Act::LeakyRelu: return kActLeakyRelu;
    case Act::Relu: return kActRelu;
  }
  throw std::runtime_error("metal: unknown activation");
}

class MetalOps : public Ops {
 public:
  MetalOps(int device, Precision precision)
      : ctx_(std::make_shared<Context>(device, precision == Precision::Fp16)) {}

  TensorPtr image(const uint8_t* data, int width, int height, int stride, int channels) override {
    if (channels != 1 && channels != 3 && channels != 4) throw std::runtime_error("unsupported pixel format");
    if (stride == 0) stride = width * channels;
    MetalPtr out = make(3, height, width);
    // The last row may be shorter than the stride.
    size_t bytes = static_cast<size_t>(stride) * (height - 1) + static_cast<size_t>(width) * channels;
    ctx_->tag(format("image %dx%d", width, height));
    Buffer<uint8_t> src(ctx_, bytes, true);
    std::memcpy(src.host(), data, bytes);
    ctx_->run("k_image", out->size(), src.view(), stride, channels, width, height, out->d());
