    const int c = f.c, h = f.h, w = f.w, total = kpts.n(), K = p.kernel, M = p.positions;
    const int dim = p.agg_w->shape[2];
    if (p.offset0_w->shape[1] != c || p.agg_w->shape[1] != c || p.sf_w->shape[0] != c)
      throw std::runtime_error("describe: shape mismatch");
    const float max_offset = static_cast<float>(std::max(h, w)) / 4.0f;
    desc->assign(static_cast<size_t>(total) * dim, 0.0f);
    ctx_->tag("describe");
    // On a normalized pyramid the head normalizes only the pixels it reads.
    const bool lazy = f.pyramid && f.pyramid->normalized && c <= 128;  // kMaxPyramidC in kernels.metal
    const PyramidArgs args = lazy ? f.pyramid_args() : PyramidArgs();
    auto part = [&](size_t i) { return f.pyramid->parts[i < f.pyramid->parts.size() ? i : 0]->d(); };

    // In chunks, so the per-keypoint work buffers (M*C floats each) stay small for any keypoint count.
    const int chunk = 8192;
    for (int begin = 0; begin < total; begin += chunk) {
      const int n = std::min(chunk, total - begin);
      const long long samples = static_cast<long long>(n) * M * c;
      Buffer<float> xy(ctx_, 2 * static_cast<size_t>(n), true), o0(ctx_, static_cast<size_t>(n) * 2 * M),
          o1(ctx_, static_cast<size_t>(n) * 2 * M), sampled(ctx_, samples), feat(ctx_, samples),
          d(ctx_, static_cast<size_t>(n) * dim);
      std::memcpy(xy.host(), kpts.xy_norm.data() + 2 * static_cast<size_t>(begin), xy.size() * sizeof(float));
      if (lazy) {
        Buffer<float> patch(ctx_, static_cast<size_t>(n) * K * K * c);
        ctx_->run("k_sddh_patch_pyramid", n * K * K, part(0), part(1), part(2), part(3), args, h, w, xy.view(), n, K,
                  patch.view());
        ctx_->run("k_sddh_offset0_patch", n * 2 * M, patch.view(), c, h, w, xy.view(), n, K,
                  ctx_->param_f32(*p.offset0_w), ctx_->param_f32(*p.offset0_b), 2 * M, o0.view());
      } else {
        ctx_->run("k_sddh_offset0", n * 2 * M, f.d(), c, h, w, xy.view(), n, K, ctx_->param_f32(*p.offset0_w),
                  ctx_->param_f32(*p.offset0_b), 2 * M, o0.view());
      }
      ctx_->run("k_sddh_offset1", n * 2 * M, o0.view(), n, 2 * M, ctx_->param_f32(*p.offset1_w), ctx_->param_f32(*p.offset1_b),
                max_offset, o1.view());
      if (lazy)
        ctx_->run("k_sddh_sample_pyramid", n * M, part(0), part(1), part(2), part(3), args, h, w, xy.view(), o1.view(), n,
                  M, sampled.view());
      else
        ctx_->run("k_sddh_sample", n * M, f.d(), c, h, w, xy.view(), o1.view(), n, M, sampled.view());
      ctx_->run("k_sddh_sf_t16", static_cast<long long>(n) * M * ((c + 15) / 16), sampled.view(), count(samples), c,
                ctx_->param_tiled(*p.sf_w, 16, true), feat.view());
      if (dim % 16 == 0)
        ctx_->run("k_sddh_aggregate_t16", n * (dim / 16), feat.view(), n, M * c, dim, ctx_->param_f32(*p.agg_w), d.view());
      else
        ctx_->run("k_sddh_aggregate", n * dim, feat.view(), n, M * c, dim, ctx_->param_f32(*p.agg_w), d.view());
      ctx_->run("k_normalize_rows", n, d.view(), n, dim);
      ctx_->sync();
      std::memcpy(desc->data() + static_cast<size_t>(begin) * dim, d.host(), d.size() * sizeof(float));
    }
  }

 private:
  // Output channels per thread for the tiled convolution kernels (instantiated for 4, 8, 16, 32).
  static int tile(int cout) {
    static const int forced = [] {
      const char* env = std::getenv("JKP_METAL_TILE");  // tuning aid
      return env ? std::atoi(env) : 0;
    }();
    if (forced == 4 || forced == 8 || forced == 16 || forced == 32) return forced;
    return cout <= 4 ? 4 : cout <= 8 ? 8 : 16;
  }

  // A tensor in the kernels' storage type.
  MetalPtr make(int c, int h, int w) { return make(c, h, w, ctx_->fp16()); }
  MetalPtr make(int c, int h, int w, bool half) { return std::make_shared<MetalTensor>(ctx_, c, h, w, half); }
  size_t elem() const { return ctx_->fp16() ? sizeof(uint16_t) : sizeof(float); }
  // Most kernels take tensors in the storage type only; the float score map of FP16 mode goes to crop and detect.
  void real_only(const MetalTensor& x) const {
    if (x.half != ctx_->fp16()) fail("operation not available for the float score map in fp16 mode");
  }

  ContextPtr ctx_;
};

