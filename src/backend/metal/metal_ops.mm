// Metal backend: host side. The kernels are in kernels.metal, one per operation, CHW layout,
// same graph and keypoint selection as the CUDA backend (src/backend/cuda/cuda_ops.cu). The RaCo
// operations (normalize, pad_reflect, detect_raco) and the XFeat operations (resize, gray_instance_norm,
// conv2d_stride2, space_to_depth, detect_xfeat) are ported from the CPU backend; detect_raco and detect_xfeat
// reuse the device-side top-k selection of detect.
//
// Precision: FP32 by default. In FP16 mode the kernels are compiled with JKP_FP16: feature maps and the
// weights of the dense network are stored as half, arithmetic stays float. The score map (the output of
// the sigmoid convolution) is kept in float so that scores do not tie, and so are keypoint selection
// and the descriptor head's own weights and buffers.
//
// Every buffer uses shared storage, so the host reads results and writes inputs in place, with no copies
// between host and device memory. Operations are encoded into one command buffer, which is committed
// and waited for only when the host needs a value (Tensor::read, selection counts, results).
//
// The shader source is compiled at run time, in safe math mode with precise math functions and with
// floating-point contraction off, so kernels compute what the CPU backend computes except for exp().
//
// The 128-channel full-resolution tensor of ALIKED (upsample_concat, then l2_normalize_crop) is a lazy
// "pyramid": the 1x1 convolution of the score head and the descriptor head compute its values from the
// four small maps where they need them, and it is stored only if something else asks for its values
// (Tensor::read in the tests, any other operation). Stored or not, FP32 results are the same.
//
// Profiling: with JKP_METAL_PROFILE=1 in the environment every dispatch runs in its own command buffer
// and its GPU time is recorded under the operation that issued it; the table goes to stderr when the
// backend is destroyed. Wall-clock times are meaningless in that mode, GPU times per dispatch are not.
