  TensorPtr conv2d(const TensorPtr& xp, const Param& weight, const Param* bias, Act act) override {
    const MetalTensor& x = dev(xp);
    const int cout = weight.shape[0], cin = weight.shape[1], k = weight.shape[2];
    if (cin != x.c || weight.shape[3] != k || k % 2 == 0) throw std::runtime_error("conv2d: shape mismatch");
    real_only(x);
    // FP16: the sigmoid layer produces the score map, which stays float (see the top of the file), and so do
    // XFeat's 65 keypoint logits (a 1x1 convolution without activation), so that its heatmap does not tie.
    const bool f32_out = ctx_->fp16() && ((act == Act::Sigmoid && cout <= 4 && (k == 1 || k == 3)) ||
                                          (act == Act::None && cout == 65 && k == 1));
    MetalPtr out = make(cout, x.h, x.w, ctx_->fp16() && !f32_out);
    ctx_->tag(format("conv%dx%d %3d->%-3d %4dx%-4d", k, k, cin, cout, x.w, x.h));
    const View b = ctx_->param(bias ? *bias : weight);  // a dummy binding without a bias
    if (k == 1 && x.pyramid && !x.pyramid->normalized && !f32_out) {
      const int t = tile(cout) > 16 ? 16 : tile(cout);
      const auto& parts = x.pyramid->parts;
      auto part = [&](size_t i) { return parts[i < parts.size() ? i : 0]->d(); };
      ctx_->run(format("k_conv1x1_pyramid_t%d", t).c_str(), static_cast<long long>((cout + t - 1) / t) * x.h * x.w,
                part(0), part(1), part(2), part(3), x.pyramid_args(), ctx_->param_tiled(weight, t), b, bias ? 1 : 0,
                cout, act_id(act), out->d());
    } else if (k == 1 || k == 3 || k == 5) {
      const int t = f32_out ? 4 : tile(cout);
      const long long threads = static_cast<long long>((cout + t - 1) / t) * x.h * x.w;
      const View w = ctx_->param_tiled(weight, t);
      ctx_->run(format("k_conv2d_t%d_k%d%s", t, k, f32_out ? "_f32" : "").c_str(), threads, x.d(), w, b, bias ? 1 : 0, cin, cout, x.h, x.w,
                act_id(act), out->d());
    } else {
      ctx_->run("k_conv2d", out->size(), x.d(), ctx_->param(weight), b, bias ? 1 : 0, cin, cout, x.h, x.w, k, act_id(act),
                out->d());
    }
    return out;
  }

