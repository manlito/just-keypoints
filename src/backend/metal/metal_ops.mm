    Buffer<float> heat(ctx_, n), score(ctx_, n);
    ctx_->run("k_xfeat_heat", h8 * w8, lg.d(), h8, w8, heat.view());
    {
      Buffer<float> tmp(ctx_, n), pooled(ctx_, n);
      ctx_->run("k_max_filter", n, heat.view(), W, H, params.window / 2, 0, tmp.view());
      ctx_->run("k_max_filter", n, tmp.view(), W, H, params.window / 2, 1, pooled.view());
      ctx_->run("k_xfeat_score", n, heat.view(), pooled.view(), rel.d(), H, W, params.threshold, score.view());
    }
    Selection select(ctx_, score.view(), n);
    const int kept = std::min(std::max(params.top_k, 0), select.count(kGreater, 0.0f));
    if (kept == 0) return;
    Buffer<int> idx(ctx_, kept), pix(ctx_, 2 * static_cast<size_t>(kept));
