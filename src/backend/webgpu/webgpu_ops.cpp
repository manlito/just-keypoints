// WebGPU backend: host side over webgpu.h. The same source builds natively against Dawn and in the
// browser against Emscripten's emdawnwebgpu (PLAN.md, phase 5). The kernels are in kernels.wgsl, a port of
// the Metal kernels, compiled at run time; same graph, pyramid and FP16 design as the Metal backend
// (src/backend/metal/metal_ops.mm), and keypoint selection on the device as on CUDA. The RaCo operations
// (normalize, pad_reflect, detect_raco) and the XFeat operations follow the Metal backend; detect_raco and
// detect_xfeat reuse the selection of detect.
//
// Every tensor is its own storage buffer. Dispatches are encoded into one compute pass and submitted only
// when the host needs a value (Tensor::read, selection counts, results) or writes a buffer: a write is
// queued after everything submitted before it, so flushing first keeps host writes in program order, and
// a buffer returned to the pool can be reused at once.
//
// Scalar arguments go into a ring of 256-byte uniform slots, one per dispatch, written just before the
// submission. Each dispatch gets its own bind group: binding 0 is its slot, buffers follow in the order
// they are passed.
//
// Precision: FP16 needs the shader-f16 feature (storage only; arithmetic is f32). WGSL cannot turn off
// contraction into fused multiply-add, so FP32 results may differ from the CPU backend in the last bits.
